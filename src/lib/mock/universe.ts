export const TICKERS = STOCK_UNIVERSE.map((stock) => stock.ticker);

export function stockProfile(ticker: string): StockProfile {
  const profile = STOCK_UNIVERSE.find((stock) => stock.ticker === ticker);
  if (!profile) throw new Error(`Unknown ticker: ${ticker}`);
  return profile;
}

export function toStock(profile: StockProfile): Stock {
  return {
    ticker: profile.ticker,
    companyName: profile.companyName,
    sector: profile.sector,
    industry: profile.industry,
    country: profile.country,
    marketCap: profile.marketCap,
    employees: profile.employees,
    peerGroup: profile.peerGroup,
  };
}
